// Scans frontend/public/assets/bikes/<folder> for each category and writes
// src/data/categoryImages.generated.ts, a slug -> image path list used to
// render each category page's photo gallery. Re-run this whenever images
// are added, removed, or a category's folder mapping changes:
//
//   node scripts/generate-category-images.mjs

import { readdirSync, statSync, writeFileSync, openSync, readSync, closeSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { categoryImageFolders } from '../src/data/categoryImageFolders.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const BIKES_DIR = join(__dirname, '..', 'public', 'assets', 'bikes');
const OUT_FILE = join(__dirname, '..', 'src', 'data', 'categoryImages.generated.ts');

const IMAGE_EXT = new Set(['.jpg', '.jpeg', '.png', '.gif']);
const MIN_BYTES = 3000; // skip tiny spacer/bullet images

// A handful of legacy files are corrupted (renamed HTML/binary junk, not
// actual images) - check the real file signature instead of trusting the
// extension, so broken thumbnails don't slip into the manifest.
function hasValidImageSignature(path) {
  const fd = openSync(path, 'r');
  try {
    const buffer = Buffer.alloc(8);
    readSync(fd, buffer, 0, 8, 0);
    if (buffer[0] === 0xff && buffer[1] === 0xd8 && buffer[2] === 0xff) return true; // JPEG
    if (buffer.subarray(0, 4).toString('hex') === '89504e47') return true; // PNG
    if (buffer.subarray(0, 3).toString('ascii') === 'GIF') return true; // GIF
    return false;
  } finally {
    closeSync(fd);
  }
}

function listImages(folder) {
  const dir = join(BIKES_DIR, folder);
  let entries;
  try {
    entries = readdirSync(dir);
  } catch {
    return [];
  }
  return entries
    .filter((name) => {
      const ext = name.slice(name.lastIndexOf('.')).toLowerCase();
      if (!IMAGE_EXT.has(ext)) return false;
      const full = join(dir, name);
      if (!statSync(full).isFile() || statSync(full).size <= MIN_BYTES) return false;
      return hasValidImageSignature(full);
    })
    .sort()
    .map((name) => `/assets/bikes/${folder}/${name}`);
}

const manifest = {};
for (const [slug, folders] of Object.entries(categoryImageFolders)) {
  const folderList = Array.isArray(folders) ? folders : [folders];
  manifest[slug] = folderList.flatMap(listImages);
}

const body = `// Generated by scripts/generate-category-images.mjs - do not edit by hand.
export const categoryImages: Record<string, string[]> = ${JSON.stringify(manifest, null, 2)};
`;

writeFileSync(OUT_FILE, body, 'utf-8');

for (const [slug, images] of Object.entries(manifest)) {
  console.log(`${slug}: ${images.length} image(s)`);
}
